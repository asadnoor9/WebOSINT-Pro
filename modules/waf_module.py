# Payloads to trigger WAF behavior
WAF_TEST_PAYLOADS = [
    "/?id=1' OR '1'='1",
    "/?search=<script>alert(1)</script>",
    "/?file=../../../etc/passwd",
    "/?cmd=;ls -la",
]


class Module(BaseModule):
    NAME = 'waf'
    DESCRIPTION = 'WAF/firewall detection: signatures + behavior + wafw00f'

    def run(self):
        results = {
            'waf_detected': False,
            'waf_name': None,
            'confidence': 'unknown',
            'signatures': [],
            'behavior': {},
        }

        base_url = f"https://{self.target}"

        # wafw00f integration
        if not self.cfg.no_external and shutil.which('wafw00f'):
            waf_result = self._run_wafw00f()
            if waf_result:
                results.update(waf_result)
                return results

        # Signature-based detection
        r_normal = self.get(base_url, verify=False)
        if not r_normal:
            return results

        detected_wafs = self._signature_detect(r_normal)

        # Behavior-based: send malicious payloads
        if not self.cfg.passive_only:
            behavior = self._behavior_detect(base_url)
            results['behavior'] = behavior
            if behavior.get('blocked_count', 0) > 0:
                results['waf_detected'] = True
                if not detected_wafs:
                    results['confidence'] = 'medium'

        if detected_wafs:
            results['waf_detected'] = True
            results['signatures'] = detected_wafs
            results['waf_name'] = detected_wafs[0] if detected_wafs else None
            results['confidence'] = 'high' if len(detected_wafs) == 1 else 'medium'

        return results

    def _run_wafw00f(self):
        try:
            cmd = ['wafw00f', self.target, '-o', '/tmp/wafw00f_out.json', '-f', 'json']
            proc = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
            output = proc.stdout + proc.stderr

            # Parse output
            waf_match = re.search(r'is behind (.+?) WAF', output, re.I)
            if waf_match:
                return {
                    'waf_detected': True,
                    'waf_name': waf_match.group(1).strip(),
                    'confidence': 'high',
                    'source': 'wafw00f',
                }
            if 'No WAF detected' in output or 'not behind a WAF' in output:
                return {'waf_detected': False, 'source': 'wafw00f'}
        except Exception as e:
            self.log(f"wafw00f error: {e}", 'debug')
        return None

    def _signature_detect(self, response):
        detected = []
        headers = {k.lower(): v.lower() for k, v in response.headers.items()}
        body = response.text.lower()
        cookies = {c.name.lower(): c.value for c in response.cookies}

        for waf_name, sigs in WAF_SIGNATURES.items():
            score = 0
            for header in sigs.get('headers', []):
                if ':' in header:
                    k, v = header.split(':', 1)
                    if k in headers and v in headers[k]:
                        score += 2
                elif header.lower() in headers:
                    score += 1

            for body_sig in sigs.get('body', []):
                if body_sig.lower() in body:
                    score += 2

            for cookie_sig in sigs.get('cookies', []):
                if cookie_sig.lower() in cookies:
                    score += 2

            if response.status_code in sigs.get('status_codes', []):
                score += 1

            if score >= 2:
                detected.append(waf_name)

        return detected

    def _behavior_detect(self, base_url):
        blocked = 0
        responses = []

        for payload in WAF_TEST_PAYLOADS[:2]:  # limit in non-aggressive
            url = f"{base_url}{payload}"
            try:
                r = self.session.get(url, timeout=self.timeout, verify=False, allow_redirects=True)
                if r:
                    responses.append({
                        'payload': payload,
                        'status': r.status_code,
                        'size': len(r.content),
                    })
                    if r.status_code in (403, 406, 429, 503):
                        blocked += 1
            except Exception:
                pass

        return {
            'blocked_count': blocked,
            'total_tested': len(WAF_TEST_PAYLOADS[:2]),
            'responses': responses,
        }
